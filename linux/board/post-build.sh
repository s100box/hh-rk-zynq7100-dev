# Give the root filesystem its own /boot/extlinux/extlinux.conf, so U-Boot's
# distro boot can boot it in place from the eMMC (mmc1).
#
# BR2_LINUX_KERNEL_INSTALL_TARGET puts uImage and the DTBs in /boot already.
# RKZ7100_ROOT_DEV overrides the root device (default /dev/mmcblk1p1). An SD
# card built from sdcard.img boots from its own FAT partition instead, with
# board/extlinux.conf (root=/dev/mmcblk0p2).
set -e

BOARD_DIR="$(dirname "$0")"
ROOT_DEV="${RKZ7100_ROOT_DEV:-/dev/mmcblk1p1}"

for f in uImage zynq-rkz7100.dtb; do
    [ -f "${TARGET_DIR}/boot/${f}" ] || {
        echo "post-build: ${TARGET_DIR}/boot/${f} is missing -- is" \
             "BR2_LINUX_KERNEL_INSTALL_TARGET set?" >&2
        exit 1
    }
done

# ⚠ uio_pdrv_genirq.of_id is not optional. That driver's device-tree match
# table is declared empty and filled in from this module parameter:
#
#     static const struct of_device_id uio_of_genirq_match[] = {
#             { /* This is filled with module_parm */ },
#             { /* Sentinel */ },
#     };
#     module_param_string(of_id, uio_of_genirq_match[0].compatible, 128, 0);
#
# so a node with compatible = "generic-uio" binds to NOTHING without it, even
# with CONFIG_UIO_PDRV_GENIRQ=y. The symptom is no /dev/uio* and not one word
# in dmesg about why. The PL's BIST engines use it for their interrupts.
UIO_ARG="uio_pdrv_genirq.of_id=generic-uio"

# ⚠ `linux` stays the default on purpose. `linux-hdmirx` names a VDMA in the
# PL, and probing that reads a PL address: with any other bitstream loaded
# the read is an AXI transaction nothing answers and THE CPU HANGS -- no oops,
# no console, and the reboot you type next goes nowhere. Selecting it is a
# deliberate act that goes with installing the capture bitstream.
mkdir -p "${TARGET_DIR}/boot/extlinux"
cat > "${TARGET_DIR}/boot/extlinux/extlinux.conf" <<EOF
# Generated by board/post-build.sh -- boots this filesystem in place.
default linux
label linux
  kernel /boot/uImage
  devicetree /boot/zynq-rkz7100.dtb
  append console=ttyPS0,115200 earlycon root=${ROOT_DEV} rootwait rw ${UIO_ARG}
label linux-usbdev
  kernel /boot/uImage
  devicetree /boot/zynq-rkz7100-usbdev.dtb
  append console=ttyPS0,115200 earlycon root=${ROOT_DEV} rootwait rw ${UIO_ARG}
label linux-hdmirx
  kernel /boot/uImage
  devicetree /boot/zynq-rkz7100-hdmirx.dtb
  append console=ttyPS0,115200 earlycon root=${ROOT_DEV} rootwait rw ${UIO_ARG}
EOF

# Load the board's bitstream at boot, if one has been installed. The fan pins
# are PL pins, so an unconfigured FPGA means no fan -- see the script.
install -m 0755 -D "${BOARD_DIR}/S15fpga" "${TARGET_DIR}/etc/init.d/S15fpga"

# lm-sensors labels, so `sensors` names the rails instead of printing in1..in6.
install -m 0644 -D "${BOARD_DIR}/sensors-rkz7100.conf"     "${TARGET_DIR}/etc/sensors.d/rkz7100.conf"

# ⚠ Do NOT add an fstab line for ${ROOT_DEV}.
#
# The same rootfs is also packed into the TFTP cpio ramdisk, and rcS runs
# `mount -a` there too: an auto entry for /dev/mmcblk1p1 on / made a RAMDISK
# boot mount the eMMC over its own root (measured -- the boot log
# shows `EXT4-fs (mmcblk1p1): mounted filesystem ... r/w` right after
# `Run /init as init process`, and df then reports the eMMC as /).
#
# Nothing is needed anyway: the kernel mounts root itself from the `root=` and
# `rw` in the append lines above, and Buildroot's stock /etc/fstab already
# carries `/dev/root / ext2 rw,noauto 0 1` for the remount case.
#
# output/target is never wiped between builds, so a root line added earlier
# would persist. Take it out.
if [ -f "${TARGET_DIR}/etc/fstab" ]; then
    sed -i "\#^${ROOT_DEV}[[:space:]]#d" "${TARGET_DIR}/etc/fstab"
fi
