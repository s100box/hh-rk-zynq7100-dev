"""Regenerate the 40-pin header (J8) constraints in both PL designs.

The 34 pins exist once, in ../../RK_ZYNQ7100_master.xdc, which was checked
against the Vivado package data pin by pin. Retyping them into each design's
XDC would be 34 more chances to transpose a pin name into one that is real,
in the right bank, and wrong -- which no tool would catch. So this reads them
back out of the master and rewrites the block between the markers in place.

Run it after touching the J8 section of the master constraints:

    python pl/tools/gen_j8_xdc.py          # rewrite, report what changed
    python pl/tools/gen_j8_xdc.py --check  # fail if anything is stale (the pre-commit hook)

The EMIO mapping is the point of the ordering, so it is fixed here:

    j8[2k]   = IO(k+1)_P = header pin 2k+4 = EMIO 18+2k = Linux gpio 72+2k
    j8[2k+1] = IO(k+1)_N = header pin 2k+3 = EMIO 19+2k = Linux gpio 73+2k
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..'))
MASTER = os.path.join(REPO, 'RK_ZYNQ7100_master.xdc')
DESIGNS = [os.path.join(REPO, 'pl', 'board', 'xdc', 'rkz7100_pl.xdc'),
           os.path.join(REPO, 'pl', 'ddr', 'xdc', 'rkz7100_ddr.xdc')]

BEGIN = '# >>> J8 pins generated by pl/tools/gen_j8_xdc.py -- do not edit by hand\n'
END = '# <<< end generated J8 pins\n'

PAT = re.compile(
    r'PACKAGE_PIN\s+(\w+)\s+IOSTANDARD\s+(\w+)\}\s*\[get_ports\s*\{gpio_([pn])\[(\d+)\]\}\]'
    r'\s*;#\s*(IO\d+_[PN])\s+J8 pin (\d+)')


def read(path):
    return io.open(path, encoding='utf-8', newline='').read()


def build_block():
    found = {}
    for m in PAT.finditer(read(MASTER)):
        pin, std, pn, k, name, hdr = m.groups()
        found[(int(k), pn)] = (pin, std, name, int(hdr))

    if len(found) != 34:
        sys.exit('gen_j8_xdc: parsed %d J8 pins from the master XDC, expected 34'
                 % len(found))
    stds = set(v[1] for v in found.values())
    if stds != {'LVCMOS33'}:
        sys.exit('gen_j8_xdc: J8 is not all LVCMOS33 in the master XDC: %s'
                 % ', '.join(sorted(stds)))

    out = [BEGIN]
    for k in range(1, 18):
        for off, pn in ((0, 'p'), (1, 'n')):
            idx = (k - 1) * 2 + off
            pin, std, name, hdr = found[(k, pn)]
            out.append('set_property -dict {PACKAGE_PIN %-4s IOSTANDARD %s} '
                       '[get_ports {j8[%d]}]  ;# %-7s J8 pin %-2d  gpio %d\n'
                       % (pin, std, idx, name, hdr, 72 + idx))
    out.append(END)
    return ''.join(out)


def main():
    check = '--check' in sys.argv[1:]
    block = build_block()
    stale = []
    for path in DESIGNS:
        s = read(path)
        if BEGIN not in s or END not in s:
            sys.exit('gen_j8_xdc: %s has no generated J8 block -- add the markers'
                     % os.path.relpath(path, REPO))
        head, rest = s.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        new = head + block + tail
        rel = os.path.relpath(path, REPO).replace(os.sep, '/')
        if new == s:
            print('  up to date  %s' % rel)
            continue
        stale.append(rel)
        if not check:
            io.open(path, 'w', encoding='utf-8', newline='').write(new)
            print('  rewrote     %s' % rel)

    if check and stale:
        sys.exit('gen_j8_xdc: stale J8 block in %s -- run pl/tools/gen_j8_xdc.py'
                 % ', '.join(stale))


if __name__ == '__main__':
    main()
