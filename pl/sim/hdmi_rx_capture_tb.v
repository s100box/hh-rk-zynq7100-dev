// hdmi_rx_capture: does it turn an ADV7611's parallel video into AXI4-Stream
// video that the Xilinx VDMA and the V4L2 pipeline behind it will accept?
//
// WHAT THIS IS BUILT TO AVOID
//
// ⚠ A pattern that does not depend on the pixel's position proves nothing.
// Every pixel carries its own coordinates -- d = {y, x} -- so a dropped
// pixel, a duplicated one, a line emitted twice or a frame that starts one
// line late is caught at the first wrong beat and NAMED. A counting check
// ("1280 beats arrived") passes on all four of those.
//
// ⚠ The stimulus is not this bench's idea of video. It is video_timing.v,
// which drives the HDMI OUTPUT and is itself checked against CEA-861
// constants written out a second time. Feeding the capture block something
// generated by the capture block's own assumptions would agree with itself
// forever.
//
// ⚠ All three modes run, and 640x480 is in the set on purpose: its HSYNC and
// VSYNC are NEGATIVE where 720p's and 1080p's are positive. A block that had
// quietly assumed a sync polarity passes two of the three.
//
// ⚠ The pixel clock and the register clock are deliberately incommensurate
// (13.468, 6.734 and 39.721 ns against 10 ns), so the snapshot handshake
// crosses a real asynchronous boundary and not a convenient integer ratio.
//
// A fourth instance starts cold in a 640x480 vertical blank, the way the
// fabric can come up on the board, and must capture the very first frame. A
// fifth has no pixel clock at all and must read as no measurement, not as a
// black 0x0 picture.
//
// THE BACKPRESSURE CASE IS THE POINT OF THE DESIGN. A capture source cannot
// be stalled, so a single low cycle on TREADY destroys a pixel. What this
// bench requires is that the damage stops there: the rest of that frame is
// abandoned, the NEXT frame is perfect to the last pixel, and the stall shows
// up in a register. A design that dropped the pixel and carried on would
// produce a permanently sheared picture and pass any test that only counted
// frames.

`timescale 1ns / 1ps

module hdmi_rx_capture_tb;

    // CEA-861, written out here from the standard rather than read from the
    // generator's parameters, so a typo in either disagrees with the other.
    localparam integer H_ACT_0 = 1280, V_ACT_0 =  720;
    localparam integer H_TOT_0 = 1650, V_TOT_0 =  750;
    localparam integer H_ACT_1 = 1920, V_ACT_1 = 1080;
    localparam integer H_TOT_1 = 2200, V_TOT_1 = 1125;
    localparam integer H_ACT_2 =  640, V_ACT_2 =  480;
    localparam integer H_TOT_2 =  800, V_TOT_2 =  525;

    // 640x480p60 is the mode with negative syncs.
    localparam H_POS_0 = 1'b1, V_POS_0 = 1'b1;
    localparam H_POS_1 = 1'b1, V_POS_1 = 1'b1;
    localparam H_POS_2 = 1'b0, V_POS_2 = 1'b0;

    // The register-side clock, shared by all three instances.
    reg ref_clk = 1'b0;
    reg ref_rstn = 1'b0;
    always #5.0 ref_clk = ~ref_clk;          // 100 MHz

    reg [2:0] done_v = 3'b000;
    reg [2:0] ok_v   = 3'b000;
    integer   errors = 0;

    task fail(input integer m, input [8*64-1:0] why);
        begin
            $display("  FAIL mode%0d: %0s", m, why);
            errors = errors + 1;
        end
    endtask

    genvar g;
    generate
    for (g = 0; g < 3; g = g + 1) begin : mode

        localparam integer H_ACT = (g == 0) ? H_ACT_0 : (g == 1) ? H_ACT_1 : H_ACT_2;
        localparam integer V_ACT = (g == 0) ? V_ACT_0 : (g == 1) ? V_ACT_1 : V_ACT_2;
        localparam integer H_TOT = (g == 0) ? H_TOT_0 : (g == 1) ? H_TOT_1 : H_TOT_2;
        localparam integer V_TOT = (g == 0) ? V_TOT_0 : (g == 1) ? V_TOT_1 : V_TOT_2;
        localparam H_POS = (g == 0) ? H_POS_0 : (g == 1) ? H_POS_1 : H_POS_2;
        localparam V_POS = (g == 0) ? V_POS_0 : (g == 1) ? V_POS_1 : V_POS_2;

        // Incommensurate with the 10 ns register clock in every mode.
        localparam real PER = (g == 0) ? 13.468 : (g == 1) ? 6.734 : 39.721;

        reg pclk = 1'b0;
        reg vt_rstn = 1'b0;
        always #(PER / 2.0) pclk = ~pclk;

        wire hs, vs, de;
        wire [11:0] x, y;

        video_timing #(.MODE(g)) vt (
            .pix_clk(pclk), .rstn(vt_rstn),
            .hsync(hs), .vsync(vs), .de(de), .x(x), .y(y), .frame_start());

        // ⚠ The pixel IS its address. Nothing here is a constant or a
        // counter that the DUT could also be producing.
        wire [23:0] pix = {y, x};

        reg  tready = 1'b1;
        reg  enable = 1'b0;
        wire [23:0] tdata;
        wire tvalid, tuser, tlast;
        wire [31:0] s0, s1, s2, s3;

        hdmi_rx_capture dut (
            .pclk(pclk), .de(de), .hs(hs), .vs(vs), .d(pix),
            .m_tdata(tdata), .m_tvalid(tvalid), .m_tready(tready),
            .m_tuser(tuser), .m_tlast(tlast),
            .ref_clk(ref_clk), .ref_rstn(ref_rstn), .enable(enable),
            .stat0(s0), .stat1(s1), .stat2(s2), .stat3(s3));

        // ----------------------------------------------------------- checker
        reg         in_frame  = 1'b0;
        reg  [11:0] ex_x = 12'd0, ex_y = 12'd0;
        integer     beats_line = 0;
        integer     lines_frame = 0;
        integer     good_frames = 0;
        integer     short_frames = 0;
        integer     stray_beats = 0;
        integer     bad_pixels = 0;
        integer     bad_eol = 0;
        reg         watching = 1'b0;   // ignore beats before the bench arms
        // ⚠ Set by the bench the moment TREADY goes low. Until the next
        // TUSER, ANY beat is a failure -- that is the whole claim the
        // abandon-the-frame design makes. Without this flag the checker
        // keeps `in_frame` set and quietly validates the continuing beats
        // against their expected coordinates, so a block that ignored the
        // stall entirely would pass.
        reg         expect_quiet = 1'b0;

        always @(posedge pclk) if (watching && tvalid && tready) begin
            if (tuser) begin
                if (in_frame) short_frames = short_frames + 1;
                expect_quiet = 1'b0;
                in_frame    = 1'b1;
                ex_x        = 12'd0;
                ex_y        = 12'd0;
                beats_line  = 0;
                lines_frame = 0;
            end

            if (!in_frame || expect_quiet) begin
                // Either a beat with no start of frame in front of it, or a
                // beat inside a frame the DUT promised to abandon.
                if (stray_beats < 4)
                    $display("  mode%0d: stray beat %06x (in_frame=%0b quiet=%0b)",
                             g, tdata, in_frame, expect_quiet);
                stray_beats = stray_beats + 1;
            end else begin
                if (tdata !== {ex_y, ex_x}) begin
                    if (bad_pixels < 4)
                        $display("  mode%0d: pixel at line %0d col %0d is %06x, expected %06x",
                                 g, ex_y, ex_x, tdata, {ex_y, ex_x});
                    bad_pixels = bad_pixels + 1;
                end
                beats_line = beats_line + 1;

                if (tlast) begin
                    if (beats_line != H_ACT) begin
                        if (bad_eol < 4)
                            $display("  mode%0d: line %0d ended after %0d beats, expected %0d",
                                     g, ex_y, beats_line, H_ACT);
                        bad_eol = bad_eol + 1;
                    end
                    beats_line  = 0;
                    lines_frame = lines_frame + 1;
                    ex_x = 12'd0;
                    ex_y = ex_y + 12'd1;
                    if (lines_frame == V_ACT) begin
                        good_frames = good_frames + 1;
                        in_frame    = 1'b0;   // the next beat must be a TUSER
                    end
                end else begin
                    if (beats_line >= H_ACT) begin
                        if (bad_eol < 4)
                            $display("  mode%0d: line %0d ran past %0d beats with no TLAST",
                                     g, ex_y, H_ACT);
                        bad_eol = bad_eol + 1;
                    end
                    ex_x = ex_x + 12'd1;
                end
            end
        end

        // --------------------------------------------------------- stimulus
        integer base_frames;
        integer stalls_before;
        reg [31:0] r0, r1, r2, r3;

        initial begin
            tready  = 1'b1;
            enable  = 1'b0;
            vt_rstn = 1'b0;
            repeat (8) @(posedge pclk);
            vt_rstn = 1'b1;

            // --- (1) enable in the MIDDLE of a frame.
            // The first beat that ever comes out must carry TUSER. A block
            // that simply started emitting on the next DE would hand the
            // VDMA a frame missing its top lines, which looks like a picture
            // shifted up rather than like a bug.
            wait (de === 1'b1);
            repeat (H_ACT / 2) @(posedge pclk);
            @(posedge ref_clk) enable = 1'b1;
            watching = 1'b1;

            // Two whole frames of the mode. Capture starts at the first frame
            // boundary after enable, so the frame in progress is allowed to be
            // missing, not allowed to be WRONG.
            repeat (2 * V_TOT * H_TOT) @(posedge pclk);

            if (good_frames < 1) fail(g, "no complete frame");
            base_frames = good_frames;

            // --- (2) one cycle of backpressure, mid-frame.
            wait (tvalid === 1'b1);
            repeat (H_ACT + 7) @(posedge pclk);
            stalls_before = s2[31:16];
            // ⚠ On the NEGEDGE. Driving TREADY from the posedge puts the
            // assignment in the same timestep as this bench's own monitor,
            // and Verilog does not order the two: the monitor can read the
            // NEW tready against the OLD tvalid and report a beat that the
            // DUT never accepted, failing a DUT that abandons the frame
            // correctly.
            @(negedge pclk);
            tready = 1'b0;
            @(negedge pclk);
            tready = 1'b1;
            expect_quiet = 1'b1;

            // The rest of that frame must be abandoned: no beat may arrive
            // without a TUSER in front of it. Then the NEXT frame must be
            // perfect, to the last pixel.
            repeat (2 * V_TOT * H_TOT) @(posedge pclk);

            if (stray_beats != 0)
                fail(g, "beats continued after a stall");
            if (good_frames <= base_frames)
                fail(g, "no clean frame after the stall");
            if (short_frames < 1)
                fail(g, "the stalled frame was not abandoned");

            // --- (3) the registers.
            @(posedge ref_clk);
            r0 = s0; r1 = s1; r2 = s2; r3 = s3;

            if (r0[15:0] !== H_ACT)
                fail(g, "h_active wrong");
            if (r0[31:16] !== H_TOT)
                fail(g, "h_total wrong");
            if (r1[15:0] !== V_ACT)
                fail(g, "v_active wrong");
            if (r1[31:16] !== V_TOT)
                fail(g, "v_total wrong");
            if (r2[31:16] === 16'd0)
                fail(g, "the stall was not counted");
            if (r3[0] !== 1'b1) fail(g, "de not seen");
            if (r3[1] !== 1'b1) fail(g, "hs not seen");
            if (r3[2] !== 1'b1) fail(g, "vs not seen");
            if (r3[3] !== V_POS) fail(g, "vs polarity misread");
            if (r3[4] !== H_POS) fail(g, "hs polarity misread");
            if (r3[6] !== 1'b1) fail(g, "the abandon flag did not stick");
            if (r3[15:8] === 8'd0)
                fail(g, "the snapshot counter never advanced");

            if (bad_pixels != 0)
                fail(g, "pixels arrived out of place");
            if (bad_eol != 0)
                fail(g, "lines did not end where they should");

            $display("  mode%0d %0dx%0d (%0dx%0d total): %0d clean frames, %0d abandoned, %0d stalls, h=%0d v=%0d ht=%0d vt=%0d pol hs=%0b vs=%0b",
                     g, H_ACT, V_ACT, H_TOT, V_TOT,
                     good_frames, short_frames, r2[31:16],
                     r0[15:0], r1[15:0], r0[31:16], r1[31:16], r3[4], r3[3]);

            ok_v[g]   = (bad_pixels == 0) && (bad_eol == 0) &&
                        (stray_beats == 0) && (good_frames > base_frames) &&
                        (short_frames >= 1);
            done_v[g] = 1'b1;
        end

    end
    endgenerate

    // ------------------------------------------------------------ cold start
    // The fabric comes up at an arbitrary point in the video. Configured
    // during a 480p vertical blank, the first DE arrives with no line period
    // confirmed yet, so the frame boundary is judged against the default
    // threshold alone -- which must sit below 480p's vertical blank (36,000
    // clocks) for that first frame to be found. Here 20,000 clocks of
    // blanking pass before the first line, and the frame's first pixel must
    // carry TUSER.
    reg        cold_clk = 1'b0;
    always #19.861 cold_clk = ~cold_clk;
    reg        cold_de = 1'b0;
    reg [23:0] cold_d = 24'd0;
    wire [23:0] cold_tdata;
    wire       cold_tvalid, cold_tuser;
    wire [31:0] c0, c1, c2, c3;
    reg        cold_done = 1'b0;
    integer    cold_first_beats = 0, cold_tusers = 0;
    reg [23:0] cold_first = 24'hxxxxxx;
    hdmi_rx_capture cold (
        .pclk(cold_clk), .de(cold_de), .hs(1'b0), .vs(1'b0), .d(cold_d),
        .m_tdata(cold_tdata), .m_tvalid(cold_tvalid), .m_tready(1'b1),
        .m_tuser(cold_tuser), .m_tlast(),
        .ref_clk(ref_clk), .ref_rstn(ref_rstn), .enable(1'b1),
        .stat0(c0), .stat1(c1), .stat2(c2), .stat3(c3));
    always @(posedge cold_clk) if (cold_tvalid) begin
        if (cold_first_beats == 0) cold_first = cold_tdata;
        cold_first_beats = cold_first_beats + 1;
        if (cold_tuser) cold_tusers = cold_tusers + 1;
    end
    initial begin : cold_stim
        integer ln, px;
        repeat (20000) @(negedge cold_clk);
        for (ln = 0; ln < V_ACT_2; ln = ln + 1) begin
            for (px = 0; px < H_ACT_2; px = px + 1) begin
                cold_de = 1'b1; cold_d = {ln[11:0], px[11:0]};
                @(negedge cold_clk);
            end
            cold_de = 1'b0;
            repeat (H_TOT_2 - H_ACT_2) @(negedge cold_clk);
        end
        repeat (100) @(negedge cold_clk);
        if (cold_first !== 24'h000000 || cold_tusers < 1)
            fail(8, "cold start: first frame missed");
        else if (cold_first_beats != H_ACT_2 * V_ACT_2)
            fail(8, "cold start: frame not whole");
        else
            $display("  cold start in 480p blanking: first frame captured whole, TUSER on pixel (0,0)");
        cold_done = 1'b1;
    end

    // ------------------------------------------------------------ dead clock
    // A pixel clock that never ticks must read as "no measurement", not as
    // "a black 0x0 picture". Same instance family, no clock at all.
    reg        dead_clk = 1'b0;
    wire [31:0] d0, d1, d2, d3;
    hdmi_rx_capture dead (
        .pclk(dead_clk), .de(1'b0), .hs(1'b0), .vs(1'b0), .d(24'd0),
        .m_tdata(), .m_tvalid(), .m_tready(1'b1), .m_tuser(), .m_tlast(),
        .ref_clk(ref_clk), .ref_rstn(ref_rstn), .enable(1'b1),
        .stat0(d0), .stat1(d1), .stat2(d2), .stat3(d3));

    initial begin
        $display("=== hdmi_rx_capture_tb");
        ref_rstn = 1'b0;
        repeat (10) @(posedge ref_clk);
        ref_rstn = 1'b1;

        wait (done_v == 3'b111 && cold_done);

        if (d3[15:8] !== 8'd0)
            fail(9, "dead clock: the snapshot counter advanced with no pixel clock");
        if ({d0, d1, d2} !== 96'd0)
            fail(9, "dead clock: status registers are not at their reset value");
        $display("  dead pixel clock: updates=%0d stat0=%08x -- no measurement, not a black frame",
                 d3[15:8], d0);

        if (ok_v !== 3'b111) errors = errors + 1;

        if (errors == 0) $display("hdmi_rx_capture_tb: PASS");
        else             $display("hdmi_rx_capture_tb: FAIL (%0d)", errors);
        $finish;
    end

    initial begin
        #400_000_000;
        $display("hdmi_rx_capture_tb: FAIL -- timeout");
        $finish;
    end

endmodule
